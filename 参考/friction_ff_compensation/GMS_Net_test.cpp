double sigmoid(double x) { return 1.0 / (1.0 + exp(-x)); }

/* ==========================================================
 * GMS-Net ǰ���ƶ�����
 * ========================================================== */
double gms_net_inference(double curr_v, double curr_a) {
    // �������޸��㡿���� C ������������ת��Ϊ��׼����������λ (m/s) �� (m/s^2)
    double v_m_s = curr_v / PULSE_PER_METER;
    double a_m_s2 = curr_a / PULSE_PER_METER;

    double X_in[3];
    X_in[0] = v_m_s / X_scale[0];          // ���������ͣ�ʹ�ñ�׼���ʵ�λ���� X_scale
    X_in[1] = a_m_s2 / X_scale[1];         // ����������
    X_in[2] = (curr_v > 0.0) ? 1.0 : ((curr_v < 0.0) ? -1.0 : 0.0);

    double a1[128];
    for (int i = 0; i < 128; i++) {
        double z1 = B1[i];
        for (int j = 0; j < 3; j++) z1 += W1[i][j] * X_in[j];
        a1[i] = tanh(z1); // ��ʱ����������ڵ��ԵķǱ��͹�����
    }

    double p_raw[14];
    for (int i = 0; i < 14; i++) {
        p_raw[i] = B2[i];
        for (int j = 0; j < 128; j++) p_raw[i] += W2[i][j] * a1[j];
    }

    double Fc = P_min[0] + (P_max[0] - P_min[0]) * sigmoid(p_raw[0]);
    double Fs = P_min[1] + (P_max[1] - P_min[1]) * sigmoid(p_raw[1]);
    double vs = P_min[2] + (P_max[2] - P_min[2]) * sigmoid(p_raw[2]);
    double sig_v = P_min[3] + (P_max[3] - P_min[3]) * sigmoid(p_raw[3]);

    double kappa[NZ];
    for (int i = 0; i < NZ; i++) kappa[i] = P_min[4 + i] + (P_max[4 + i] - P_min[4 + i]) * sigmoid(p_raw[4 + i]);

    double nu[NZ]; double sum_exp = 0.0;
    for (int i = 0; i < NZ; i++) {
        double safe_raw = p_raw[9 + i];
        if (safe_raw > 20.0) safe_raw = 20.0;
        sum_exp += exp(safe_raw);
    }
    for (int i = 0; i < NZ; i++) {
        double safe_raw = p_raw[9 + i];
        if (safe_raw > 20.0) safe_raw = 20.0;
        nu[i] = exp(safe_raw) / (sum_exp + 1e-8);
    }

    // ���ﴫ�������ڲ��ݱ�ʱҲ��ʹ��������λ���ٶ� v_m_s
    double lambda = 3.4534 / (1.0 - ZETA); double gamma = lambda;
    double s_plus = Fc + (Fs - Fc) * exp(-pow(v_m_s / (vs + 1e-6), 2));

    int n_sub = 10; double dt_sub = 0.001 / n_sub;
    for (int sub = 0; sub < n_sub; sub++) {
        for (int i = 0; i < NZ; i++) {
            double z_max = (nu[i] / (kappa[i] + 1e-6)) * s_plus;
            if (z_max < 1e-8) z_max = 1e-8;
            double z_ratio = z_net[i] / z_max;
            double eta_A = 1.0 - 0.5 * tanh(lambda * (z_ratio + ZETA)) + 0.5 * tanh(lambda * (z_ratio - ZETA));
            double eta_B = 0.5 + 0.5 * tanh(gamma * z_ratio * (v_m_s / (vs + 1e-6)));
            double eta = eta_A * eta_B;
            double dzdt = v_m_s - eta * fabs(v_m_s) * z_ratio;
            z_net[i] += dzdt * dt_sub;
            if (z_net[i] > z_max)  z_net[i] = z_max;
            if (z_net[i] < -z_max) z_net[i] = -z_max;
        }
    }

    double T_fric = sig_v * v_m_s;
    for (int i = 0; i < NZ; i++) T_fric += kappa[i] * z_net[i];

    return T_fric; // ��������Ħ������ (Nm)
}

